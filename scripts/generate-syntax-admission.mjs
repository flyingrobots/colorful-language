#!/usr/bin/env node

import {
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { parseSyntaxSchema } from "./ir-schema-policy.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const COMPATIBILITY_PATH = "contracts/colorful/syntax-compatibility.v1.json";
const OUTPUT_PATHS = Object.freeze([
  "consumers/generated/syntax-admission-v1.mjs",
  "consumers/independent-ir-report/generated/syntax-admission-v1.mjs",
]);
const BUILT_INS = new Set(["Boolean", "Float", "ID", "Int", "String"]);

function fail(message) {
  throw new Error(`generate-syntax-admission: ${message}`);
}

function namedType(reference) {
  return reference.replaceAll(/[\[\]!]/gu, "");
}

function compileSchema(id, sdl) {
  if (typeof id !== "string" || id.length === 0) {
    fail("generation id must be a non-empty string");
  }
  const parsed = parseSyntaxSchema(sdl);
  const root = parsed.get("DocumentAnalysis");
  if (root?.kind !== "type") {
    fail(`generation ${id} has no DocumentAnalysis object`);
  }
  const definitions = {};
  for (const [name, definition] of parsed) {
    if (definition.kind === "enum") {
      definitions[name] = {
        kind: "enum",
        values: [...definition.values],
      };
      continue;
    }
    const fields = [];
    for (const [fieldName, reference] of definition.fields) {
      const target = namedType(reference);
      if (!BUILT_INS.has(target) && !parsed.has(target)) {
        fail(
          `generation ${id} field ${name}.${fieldName} refers to missing type ${target}`,
        );
      }
      fields.push([fieldName, reference]);
    }
    definitions[name] = { kind: "type", fields };
  }
  return { id, definitions };
}

function validateGenerationInputs(currentGenerationId, generations) {
  if (!Array.isArray(generations) || generations.length === 0) {
    fail("at least one generation is required");
  }
  const ids = new Set();
  for (const generation of generations) {
    if (
      generation === null ||
      typeof generation !== "object" ||
      typeof generation.id !== "string" ||
      typeof generation.sdl !== "string"
    ) {
      fail("each generation must provide string id and sdl fields");
    }
    if (ids.has(generation.id)) {
      fail(`duplicate generation id ${generation.id}`);
    }
    ids.add(generation.id);
  }
  if (!ids.has(currentGenerationId)) {
    fail(`current generation ${currentGenerationId} is not present`);
  }
}

export function renderSyntaxAdmission({
  currentGenerationId,
  generations,
}) {
  validateGenerationInputs(currentGenerationId, generations);
  const compiled = generations.map(({ id, sdl }) => compileSchema(id, sdl));
  const generationIds = compiled.map(({ id }) => id);
  const definitions = Object.fromEntries(
    compiled.map(({ id, definitions: schema }) => [id, schema]),
  );
  const rootFields = [
    ...new Set(
      compiled.flatMap(({ definitions: schema }) =>
        schema.DocumentAnalysis.fields.map(([field]) => field),
      ),
    ),
  ];

  return `// @generated by scripts/generate-syntax-admission.mjs.
// Structural authority: contracts/colorful/syntax-compatibility.v1.json and
// the GraphQL SDL selected by each compatibility generation. Do not edit.

export const CURRENT_SYNTAX_GENERATION = ${JSON.stringify(currentGenerationId)};
export const SYNTAX_GENERATION_IDS = Object.freeze(${JSON.stringify(generationIds)});
export const SYNTAX_ADMISSION_REASON_CODES = Object.freeze({
  INVALID_VALUE: "INVALID_VALUE",
  UNKNOWN_FIELD: "UNKNOWN_FIELD",
});

const ROOT_FIELDS = new Set(${JSON.stringify(rootFields)});
const GENERATIONS = ${JSON.stringify(definitions, null, 2)};
const GRAPHQL_INT_MIN = -2147483648;
const GRAPHQL_INT_MAX = 2147483647;

export class SyntaxAdmissionError extends Error {
  constructor(
    path,
    reason,
    reasonCode = SYNTAX_ADMISSION_REASON_CODES.INVALID_VALUE,
  ) {
    const location = path.length === 0 ? "artifact" : path;
    super(\`\${location} \${reason}\`);
    this.name = "SyntaxAdmissionError";
    this.code = "E_SYNTAX_SHAPE";
    this.path = path;
    this.location = location;
    this.reasonCode = reasonCode;
  }
}

function defaultReject(_path, _reason, error) {
  throw error;
}

function rejectWith(
  reject,
  path,
  reason,
  reasonCode = SYNTAX_ADMISSION_REASON_CODES.INVALID_VALUE,
) {
  const error = new SyntaxAdmissionError(path, reason, reasonCode);
  reject(path, reason, error);
  throw new TypeError("syntax admission rejection callback must throw");
}

function generationSchema(generationId, reject) {
  if (!Object.hasOwn(GENERATIONS, generationId)) {
    rejectWith(
      reject,
      "",
      \`uses unknown syntax generation \${generationId}\`,
    );
  }
  return GENERATIONS[generationId];
}

function isRecord(value) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    return false;
  }
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function fieldPath(parent, field) {
  return parent.length === 0 ? field : \`\${parent}.\${field}\`;
}

function parseReference(reference) {
  const required = reference.endsWith("!");
  const core = required ? reference.slice(0, -1) : reference;
  if (core.startsWith("[")) {
    const itemSource = core.slice(1, -1);
    return {
      kind: "list",
      required,
      item: parseReference(itemSource),
    };
  }
  return { kind: "named", required, name: core };
}

function prepareSchemas() {
  for (const schema of Object.values(GENERATIONS)) {
    for (const definition of Object.values(schema)) {
      if (definition.kind !== "type") continue;
      definition.fieldNames = new Set(
        definition.fields.map(([field]) => field),
      );
      definition.fields = definition.fields.map(([field, reference]) => [
        field,
        parseReference(reference),
      ]);
    }
  }
}

prepareSchemas();

function validateBuiltIn(value, name, path, reject) {
  if (name === "String" || name === "ID") {
    if (typeof value !== "string") {
      rejectWith(reject, path, "must be a string");
    }
    return;
  }
  if (name === "Int") {
    if (
      !Number.isSafeInteger(value) ||
      value < GRAPHQL_INT_MIN ||
      value > GRAPHQL_INT_MAX
    ) {
      rejectWith(reject, path, "must be a signed GraphQL Int");
    }
    return;
  }
  if (name === "Float") {
    if (typeof value !== "number" || !Number.isFinite(value)) {
      rejectWith(reject, path, "must be a finite number");
    }
    return;
  }
  if (name === "Boolean") {
    if (typeof value !== "boolean") {
      rejectWith(reject, path, "must be a boolean");
    }
    return;
  }
  rejectWith(reject, path, \`uses unsupported built-in type \${name}\`);
}

function validateNamed(value, name, schema, path, reject) {
  if (
    name === "String" ||
    name === "ID" ||
    name === "Int" ||
    name === "Float" ||
    name === "Boolean"
  ) {
    validateBuiltIn(value, name, path, reject);
    return;
  }
  const definition = schema[name];
  if (definition === undefined) {
    rejectWith(reject, path, \`refers to missing type \${name}\`);
  }
  if (definition.kind === "enum") {
    if (typeof value !== "string" || !definition.values.includes(value)) {
      rejectWith(reject, path, \`must be a member of \${name}\`);
    }
    return;
  }
  if (!isRecord(value)) {
    rejectWith(reject, path, "must be an object");
  }
  for (const field of Object.keys(value)) {
    if (!definition.fieldNames.has(field)) {
      rejectWith(
        reject,
        fieldPath(path, field),
        "is not part of the contract",
        SYNTAX_ADMISSION_REASON_CODES.UNKNOWN_FIELD,
      );
    }
  }
  for (const [field, parsedReference] of definition.fields) {
    const childPath = fieldPath(path, field);
    if (!Object.hasOwn(value, field)) {
      rejectWith(reject, childPath, "is required by the contract shape");
    }
    validateReference(value[field], parsedReference, schema, childPath, reject);
  }
}

function validateReference(value, reference, schema, path, reject) {
  if (value === null) {
    if (reference.required) {
      rejectWith(reject, path, "must not be null");
    }
    return;
  }
  if (reference.kind === "list") {
    if (!Array.isArray(value)) {
      rejectWith(reject, path, "must be an array");
    }
    for (const [index, item] of value.entries()) {
      validateReference(item, reference.item, schema, \`\${path}[\${index}]\`, reject);
    }
    return;
  }
  validateNamed(value, reference.name, schema, path, reject);
}

export function validateSyntaxEnvelope(value, reject = defaultReject) {
  if (!isRecord(value)) {
    rejectWith(reject, "", "must be an object");
  }
  for (const field of Object.keys(value)) {
    if (!ROOT_FIELDS.has(field)) {
      rejectWith(
        reject,
        field,
        "is not part of the contract",
        SYNTAX_ADMISSION_REASON_CODES.UNKNOWN_FIELD,
      );
    }
  }
  for (const field of ["contractVersion", "schemaHash", "vocabularyHash"]) {
    if (!Object.hasOwn(value, field)) {
      rejectWith(reject, field, "is required by the contract shape");
    }
    validateBuiltIn(value[field], "String", field, reject);
  }
}

export function validateSyntaxShape(
  value,
  generationId,
  reject = defaultReject,
) {
  const schema = generationSchema(generationId, reject);
  validateNamed(value, "DocumentAnalysis", schema, "", reject);
}

export function syntaxGenerationHasField(
  generationId,
  typeName,
  fieldName,
) {
  const schema = generationSchema(generationId, defaultReject);
  const definition = schema?.[typeName];
  return (
    definition?.kind === "type" &&
    definition.fields.some(([field]) => field === fieldName)
  );
}
`;
}

function sameIdentity(left, right) {
  return (
    left.contractVersion === right.contractVersion &&
    left.schemaHash === right.schemaHash &&
    left.vocabularyHash === right.vocabularyHash
  );
}

export function generateSyntaxAdmission(outputRoot = ROOT) {
  const compatibility = JSON.parse(
    readFileSync(path.join(ROOT, COMPATIBILITY_PATH), "utf8"),
  );
  const current = compatibility.generations.find((generation) =>
    sameIdentity(generation.identity, compatibility.currentIdentity)
  );
  if (current === undefined) {
    fail("compatibility manifest does not identify its current generation");
  }
  const source = renderSyntaxAdmission({
    currentGenerationId: current.id,
    generations: compatibility.generations.map((generation) => ({
      id: generation.id,
      sdl: readFileSync(
        path.join(ROOT, generation.artifacts.schema),
        "utf8",
      ),
    })),
  });
  for (const relativePath of OUTPUT_PATHS) {
    const output = path.join(outputRoot, relativePath);
    mkdirSync(path.dirname(output), { recursive: true });
    writeFileSync(output, source);
  }
  return [...OUTPUT_PATHS];
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.length === 0) {
    generateSyntaxAdmission();
  } else if (args.length === 2 && args[0] === "--output-root") {
    generateSyntaxAdmission(path.resolve(args[1]));
  } else {
    process.stderr.write(
      "usage: generate-syntax-admission.mjs [--output-root PATH]\n",
    );
    process.exitCode = 2;
  }
}
